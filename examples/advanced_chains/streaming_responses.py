def example_streaming_with_parser() -> None:
    """
    Demonstrate streaming through a complete LCEL chain with output parsing.
    
    Type Flow: 
    Dict[str, str] → ChatPromptTemplate → List[BaseMessage] → 
    FakeStreamingListLLM → AIMessage chunks → StrOutputParser → str chunks
    
    The StrOutputParser converts AIMessage chunks to string chunks while
    maintaining streaming behavior.
    
    Source: libs/core/tests/unit_tests/runnables/test_runnable.py:1851
    """
    print("\n" + "=" * 80)
    print("Example 3: Streaming with Output Parser")
    print("=" * 80)
    
    try:
        # Create chat prompt template
        prompt = ChatPromptTemplate.from_messages([
            ("system", "You are a helpful coding assistant."),
            ("human", "{question}")
        ])
        
        # Create streaming LLM
        llm = FakeStreamingListLLM(
            responses=[
                "Here is a simple Python function:\n\ndef greet(name):\n    "
                "return f'Hello, {name}!'\n\nThis function takes a name and "
                "returns a greeting."
            ]
        )
        
        # Create string output parser
        parser = StrOutputParser()
        
        # Build LCEL chain: prompt | llm | parser
        chain = prompt | llm | parser
        
        print("\nQuestion: Write a simple Python function")
        print("Streaming response:\n")
        
        # Stream with parser
        full_response = ""
        for chunk in chain.stream({"question": "Write a simple Python function"}):
            # Parser converts message chunks to string chunks
            print(chunk, end="", flush=True)
            full_response += chunk
        
        print(f"\n\n✓ Streaming complete")
        print(f"  Total response length: {len(full_response)} characters")
        
    except Exception as e:
        print(f"\n✗ Error in parser streaming: {e}")
        print(f"  Error type: {type(e).__name__}")


