def example_streaming_with_callback() -> None:
    """
    Demonstrate streaming using a custom callback handler.
    
    Callbacks provide an alternative streaming mechanism where tokens are
    intercepted via the on_llm_new_token callback method. This is useful for:
    - Custom token processing logic
    - Logging or monitoring token generation
    - Implementing custom display logic
    
    Source: libs/core/langchain_core/callbacks/base.py
    Source: Agent Action Plan section 0.4.1 - Custom callback patterns
    """
    print("\n" + "=" * 80)
    print("Example 2: Streaming with Custom Callback Handler")
    print("=" * 80)
    
    try:
        prompt = PromptTemplate.from_template(
            "Explain in simple terms: {topic}"
        )
        
        llm = FakeStreamingListLLM(
            responses=[
                "A callback handler is a class that intercepts events during chain execution, "
                "allowing you to add custom behavior like logging, monitoring, or real-time "
                "token processing during streaming."
            ]
        )
        
        # Create custom callback handler
        callback = StreamingCallbackHandler()
        
        # Create chain
        chain = prompt | llm
        
        print("\nTopic: What is a callback handler?")
        print("Streaming with callback: ", end="", flush=True)
        
        # Invoke with callback in config
        # The callback's on_llm_new_token will be called for each token
        response = chain.invoke(
            {"topic": "What is a callback handler?"},
            {"callbacks": [callback]}
        )
        
        print(f"\n✓ Complete response length: {len(response)} characters")
        print(f"  Tokens captured by callback: {callback.token_count}")
        
    except Exception as e:
        print(f"\n✗ Error in callback streaming: {e}")
        print(f"  Error type: {type(e).__name__}")


