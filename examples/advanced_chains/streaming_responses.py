def example_basic_streaming() -> None:
    """
    Demonstrate basic streaming using the .stream() method on a simple LCEL chain.
    
    Type Flow: Dict[str, str] → PromptTemplate → str → FakeStreamingListLLM → str chunks
    
    The .stream() method returns an iterator that yields response chunks as they
    are generated, allowing token-by-token display.
    
    Source: libs/core/tests/unit_tests/runnables/test_runnable.py:1050
    """
    print("=" * 80)
    print("Example 1: Basic Streaming with .stream()")
    print("=" * 80)
    
    try:
        # Create a simple prompt template
        prompt = PromptTemplate.from_template(
            "You are a helpful assistant. Answer the following question: {question}"
        )
        
        # Create a fake streaming LLM for demonstration
        # This simulates token-by-token generation without requiring API keys
        llm = FakeStreamingListLLM(
            responses=[
                "Streaming allows you to receive and display tokens as they are generated, "
                "providing a more responsive user experience instead of waiting for the "
                "complete response."
            ]
        )
        
        # Create LCEL chain: prompt | llm
        # Type flow: Dict → PromptValue → Iterator[str]
        chain = prompt | llm
        
        # Invoke with streaming
        print("\nQuestion: What is streaming in LangChain?")
        print("Streaming response: ", end="", flush=True)
        
        # Collect chunks for analysis
        chunks = []
        for chunk in chain.stream({"question": "What is streaming in LangChain?"}):
            # Each chunk is a token string
            print(chunk, end="", flush=True)
            chunks.append(chunk)
        
        print(f"\n\n✓ Received {len(chunks)} chunks")
        print(f"  First chunk: '{chunks[0] if chunks else 'N/A'}'")
        print(f"  Last chunk: '{chunks[-1] if chunks else 'N/A'}'")
        
    except Exception as e:
        print(f"\n✗ Error in basic streaming: {e}")
        print(f"  Error type: {type(e).__name__}")


