async def example_async_streaming() -> None:
    """
    Demonstrate asynchronous streaming using .astream() method.
    
    Async streaming is essential for:
    - Non-blocking operations in async applications
    - Concurrent request handling in web servers
    - Integration with async frameworks (FastAPI, aiohttp, etc.)
    
    Type Flow: Dict → PromptTemplate → AsyncIterator[str]
    
    Source: libs/core/tests/unit_tests/runnables/test_runnable.py:1958
    """
    print("\n" + "=" * 80)
    print("Example 4: Async Streaming with .astream()")
    print("=" * 80)
    
    try:
        prompt = PromptTemplate.from_template(
            "Describe the benefits of: {concept}"
        )
        
        llm = FakeStreamingListLLM(
            responses=[
                "Async streaming provides non-blocking I/O operations, allowing your "
                "application to handle multiple concurrent requests efficiently. "
                "It's particularly valuable in web servers where you need to serve "
                "many users simultaneously without thread-per-request overhead."
            ]
        )
        
        chain = prompt | llm
        
        print("\nConcept: Async streaming")
        print("Async streaming response: ", end="", flush=True)
        
        # Async iteration over stream
        chunks_received = 0
        async for chunk in chain.astream({"concept": "async streaming"}):
            print(chunk, end="", flush=True)
            chunks_received += 1
            # Simulate async processing (e.g., writing to async database)
            await asyncio.sleep(0.01)
        
        print(f"\n\n✓ Async streaming complete")
        print(f"  Chunks received: {chunks_received}")
        
    except Exception as e:
        print(f"\n✗ Error in async streaming: {e}")
        print(f"  Error type: {type(e).__name__}")


