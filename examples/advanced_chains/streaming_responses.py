# Example 6: Performance Comparison - Streaming vs Non-Streaming
# ==============================================================================

def example_performance_comparison() -> None:
    """
    Compare performance characteristics of streaming vs non-streaming invocation.
    
    Key metrics:
    - Time to first token (TTFT): How quickly user sees initial response
    - Total time: Overall response generation time
    - User experience: Perceived responsiveness
    
    Streaming advantage: Lower perceived latency due to incremental display
    Non-streaming advantage: Simpler implementation for batch processing
    
    Source: Agent Action Plan section 0.4.1 - Performance demonstration
    """
    print("\n" + "=" * 80)
    print("Example 6: Performance Comparison")
    print("=" * 80)
    
    try:
        prompt = PromptTemplate.from_template("Explain: {topic}")
        llm = FakeStreamingListLLM(
            responses=[
                "Performance comparison reveals that streaming provides better user "
                "experience through incremental display, even if total generation "
                "time is similar. Users perceive streaming responses as faster "
                "because they see progress immediately."
            ]
        )
        chain = prompt | llm
        
        # Non-streaming invocation
        print("\n1. Non-streaming invocation:")
        print("   Waiting for complete response...", end="", flush=True)
        start_time = time.time()
        response = chain.invoke({"topic": "streaming performance"})
        end_time = time.time()
        print(f" Done!")
        print(f"   Time to complete: {(end_time - start_time) * 1000:.2f}ms")
        print(f"   Response length: {len(response)} characters")
        print(f"   User sees nothing until: {(end_time - start_time) * 1000:.2f}ms")
        
        # Streaming invocation
        print("\n2. Streaming invocation:")
        print("   Streaming response: ", end="", flush=True)
        start_time = time.time()
        first_token_time = None
        chunks = []
        
        for i, chunk in enumerate(chain.stream({"topic": "streaming performance"})):
            if i == 0:
                first_token_time = time.time()
            chunks.append(chunk)
        
        end_time = time.time()
        print()
        
        ttft = (first_token_time - start_time) * 1000 if first_token_time else 0
        total_time = (end_time - start_time) * 1000
        
        print(f"   Time to first token (TTFT): {ttft:.2f}ms")
        print(f"   Total time: {total_time:.2f}ms")
        print(f"   Chunks received: {len(chunks)}")
        print(f"   User sees content starting at: {ttft:.2f}ms ← Much better UX!")
        
        print("\n✓ Performance comparison complete")
        print("  Key insight: Streaming reduces perceived latency")
        
    except Exception as e:
        print(f"\n✗ Error in performance comparison: {e}")
        print(f"  Error type: {type(e).__name__}")


