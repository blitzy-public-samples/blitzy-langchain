def example_streaming_with_passthrough() -> None:
    """
    Demonstrate streaming through complex chains using RunnablePassthrough.
    
    RunnablePassthrough allows you to pass data through a chain while applying
    transformations, which is useful for:
    - Maintaining context while processing
    - Building complex multi-step chains
    - Implementing RAG (Retrieval-Augmented Generation) patterns
    
    Type Flow: Dict → RunnablePassthrough → PromptTemplate → str chunks
    
    Source: libs/core/tests/unit_tests/runnables/test_runnable.py:1050
    Source: Agent Action Plan section 0.3.1 - Complex chain streaming
    """
    print("\n" + "=" * 80)
    print("Example 5: Streaming with RunnablePassthrough")
    print("=" * 80)
    
    try:
        # Create a chain that passes through the question and adds context
        prompt = PromptTemplate.from_template(
            "Context: {context}\n\nQuestion: {question}\n\nAnswer:"
        )
        
        llm = FakeStreamingListLLM(
            responses=[
                "Based on the provided context, LangChain is designed with streaming "
                "as a first-class feature. Every runnable supports streaming through "
                "the .stream() and .astream() methods, making it easy to build "
                "responsive applications."
            ]
        )
        
        # Build complex chain with passthrough
        # RunnablePassthrough.assign adds new keys while preserving existing ones
        chain = (
            RunnablePassthrough.assign(
                context=lambda x: "LangChain is a framework for building LLM applications."
            )
            | prompt
            | llm
        )
        
        print("\nQuestion: How does LangChain handle streaming?")
        print("Streaming response: ", end="", flush=True)
        
        for chunk in chain.stream({"question": "How does LangChain handle streaming?"}):
            print(chunk, end="", flush=True)
        
        print("\n\n✓ Complex chain streaming complete")
        
    except Exception as e:
        print(f"\n✗ Error in passthrough streaming: {e}")
        print(f"  Error type: {type(e).__name__}")


