# Custom Streaming Callback Handler
# ==============================================================================

class StreamingCallbackHandler(BaseCallbackHandler):
    """
    Custom callback handler that processes streaming tokens in real-time.
    
    This handler demonstrates how to capture and process tokens as they arrive
    from the LLM, enabling custom streaming behaviors like real-time display,
    logging, or token-level analysis.
    
    Source: libs/core/langchain_core/callbacks/base.py
    Source: Agent Action Plan section 0.4.1 - Callback-based streaming patterns
    """
    
    def __init__(self) -> None:
        """Initialize the streaming callback handler with empty token storage."""
        super().__init__()
        self.tokens: List[str] = []
        self.token_count: int = 0
    
    def on_llm_new_token(self, token: str, **kwargs: Any) -> None:
        """
        Called when a new token is generated by the LLM.
        
        Args:
            token: The newly generated token string
            **kwargs: Additional metadata about the token generation
                - chunk: The message chunk if available
                - run_id: Unique identifier for this LLM run
        
        Note: This method is called synchronously during streaming, so avoid
        blocking operations here.
        """
        self.tokens.append(token)
        self.token_count += 1
        # Display token immediately with flush for real-time output
        print(token, end="", flush=True)
    
    def on_llm_end(self, response: Any, **kwargs: Any) -> None:
        """
        Called when LLM finishes generating the complete response.
        
        Args:
            response: The complete LLM response object
            **kwargs: Additional run metadata
        """
        print()  # New line after streaming completes
        print(f"\n[Streaming complete: {self.token_count} tokens received]")
    
    def reset(self) -> None:
        """Reset the handler state for reuse."""
        self.tokens = []
        self.token_count = 0


